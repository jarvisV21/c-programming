#include <stdio.h>
int main() {
    // this program for practice of data types in C programing
    int age = 21;
    float height = 5.9;
    double pi = 3.14159;
    char initial = 'H';
    printf("Age = %d\n", age);
    printf("Height = %.1f\n", height);
    printf("Pi = %.101f\n", pi);
    printf("Initial = %c\n", initial);
    return 0;
}